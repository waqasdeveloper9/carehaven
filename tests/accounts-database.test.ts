import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { PGlite } from '@electric-sql/pglite';

test('account provisioning, setup gate, financial isolation, retries, and child photos use actual PostgreSQL policies', async () => {
 const db = new PGlite();
 try {
  await db.exec(`
   create role anon; create role authenticated; create role service_role bypassrls;
   create schema auth; create schema storage;
   create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb default '{}',raw_app_meta_data jsonb default '{}',email_confirmed_at timestamptz,encrypted_password text,last_sign_in_at timestamptz);
   create table storage.objects(name text,bucket_id text,owner_id text,metadata jsonb);
   create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   create function auth.role() returns text language sql stable as $$select current_setting('request.jwt.claim.role',true)$$;
   grant usage on schema public,auth to authenticated,service_role;
   grant execute on function auth.uid(),auth.role() to authenticated,service_role;
  `);
  for (const file of ['202610160001_core.sql','202610160002_admin_bootstrap.sql','202610160003_accounts_and_child_photos.sql']) await db.exec(await readFile(new URL(`../supabase/migrations/${file}`,import.meta.url),'utf8'));
  await db.exec('grant all on all tables in schema public to service_role');
  await db.exec(`insert into public.app_settings(key,value) values('photo_bucket','"child-photos"')`);
  const admin = randomUUID(), staff = randomUUID(), sponsor = randomUUID(), other = randomUUID();
  const request = randomUUID(), donationRequest = randomUUID();
  const authUser = async (id:string,email:string,requestId?:string) => db.query<Record<string,unknown>>(`insert into auth.users(id,email,email_confirmed_at,encrypted_password,raw_app_meta_data) values($1,$2,now(),'random-initial-password',$3::jsonb)`,[id,email,JSON.stringify(requestId?{provisioning_request:requestId,provisioned_by:admin}:{})]);
  await authUser(admin,'owner@example.test');
  await db.query<Record<string,unknown>>(`update public.profiles set role='admin',status='approved' where id=$1`,[admin]);
  const as = async (role:string,id:string='') => {await db.exec('reset role');await db.query<Record<string,unknown>>(`select set_config('request.jwt.claim.sub',$1,false),set_config('request.jwt.claim.role',$2,false)`,[id,role]);if(role!=='postgres')await db.exec(`set role ${role}`);};
  const rpc = (name:string,args:unknown[]) => db.query<Record<string,unknown>>(`select public.${name}(${args.map((_,index)=>`$${index+1}`).join(',')}) as result`,args);
  const bool = async (permission:string) => (await rpc('has_permission',[staff,permission])).rows[0].result;
  await authUser(staff,'staff@example.test',request);
  await as('service_role');
  const staffPayload={role:'staff_user',full_name:'Care Staff',email:'staff@example.test',phone:''};
  await rpc('provision_account',[admin,staff,request,staffPayload]);
  await as('authenticated',staff);
  assert.equal(await bool('manage_orphans'),false,'invited staff is locked out until a real password change');
  await assert.rejects(rpc('set_permission',[staff,'manage_financials',true]),/Administrator access required/);
  await as('postgres');
  await db.query<Record<string,unknown>>(`update auth.users set last_sign_in_at=now() where id=$1`,[staff]);
  assert.equal((await db.query<Record<string,unknown>>(`select first_login_at from public.profiles where id=$1`,[staff])).rows[0].first_login_at,null,'opening the welcome email is not a completed first login');
  await db.query<Record<string,unknown>>(`update auth.users set encrypted_password='chosen-private-password' where id=$1`,[staff]);
  await as('authenticated',staff);
  assert.equal(await bool('manage_orphans'),true);
  assert.equal(await bool('assign_donors'),true);
  for(const permission of ['view_financials','manage_financials','approve_donors','run_audits'])assert.equal(await bool(permission),false);
  await as('postgres');
  await db.query<Record<string,unknown>>(`update auth.users set last_sign_in_at=now() where id=$1`,[staff]);
  assert.ok((await db.query<Record<string,unknown>>(`select first_login_at from public.profiles where id=$1`,[staff])).rows[0].first_login_at);
  await authUser(sponsor,'sponsor@example.test',donationRequest);
  await as('service_role');
  const sponsorPayload={role:'donor',full_name:'New Sponsor',email:'sponsor@example.test',phone:'',donation:{amount:2500,description:'First contribution'}};
  await rpc('provision_account',[admin,sponsor,donationRequest,sponsorPayload]);
  await rpc('provision_account',[admin,sponsor,donationRequest,sponsorPayload]);
  const ledger=await db.query<Record<string,unknown>>(`select amount_in from public.financial_ledger where donor_id=$1`,[sponsor]);
  assert.equal(ledger.rows.length,1,'replaying the same request does not duplicate the donation');
  assert.equal(Number(ledger.rows[0].amount_in),2500);
  await assert.rejects(rpc('provision_account',[admin,sponsor,donationRequest,{...sponsorPayload,full_name:'Different Sponsor'}]),/different account details/);
  await assert.rejects(rpc('provisioning_context',[admin,randomUUID(),'sponsor@example.test']),/already exists/);
  const claim = await rpc('claim_account_invitation',[admin,sponsor]);
  assert.ok(claim.rows[0].result);
  assert.equal((await rpc('claim_account_invitation',[admin,sponsor])).rows[0].result,null,'concurrent sends share a lease');
  await rpc('finish_account_invitation',[admin,sponsor,claim.rows[0].result,false]);
  assert.equal((await db.query<Record<string,unknown>>(`select delivery_status from public.account_invitations where user_id=$1`,[sponsor])).rows[0].delivery_status,'failed');
  await as('authenticated',staff);
  await assert.rejects(rpc('post_donation',[sponsor,100,'Unauthorized contribution',randomUUID()]),/Permission denied/);
  assert.equal((await db.query<Record<string,unknown>>('select * from public.financial_ledger')).rows.length,0,'staff cannot read financials by direct database requests');
  await assert.rejects(rpc('provision_account',[admin,sponsor,donationRequest,sponsorPayload]),/permission denied/);
  const child=randomUUID();
  await db.query<Record<string,unknown>>(`insert into public.orphans(id,full_name,date_of_birth,gender) values($1,'A Child','2020-01-01','Female')`,[child]);
  await assert.rejects(db.query<Record<string,unknown>>(`update public.orphans set picture_url='another-user/private.jpg' where id=$1`,[child]),/Upload a child photo owned/);
  await as('postgres');
  await db.query<Record<string,unknown>>(`insert into storage.objects values($1,'child-photos',$2,'{"mimetype":"image/jpeg"}')`,[`${staff}/photo.jpg`,staff]);
  await as('authenticated',staff);
  await db.query<Record<string,unknown>>(`update public.orphans set picture_url=$1,full_name='Updated Child' where id=$2`,[`${staff}/photo.jpg`,child]);
  await as('authenticated',admin);
  assert.equal((await rpc('has_permission',[admin,'manage_financials'])).rows[0].result,true,'administrator rights are inherited');
  await rpc('set_permission',[staff,'manage_orphans',false]);
  await as('authenticated',staff);
  assert.equal(await bool('manage_orphans'),false,'revocation takes effect on the next request');
  await as('postgres');
  await authUser(other,'other@example.test');
  await db.query<Record<string,unknown>>(`update public.profiles set status='approved' where id=$1`,[other]);
  await db.query<Record<string,unknown>>(`update auth.users set encrypted_password='sponsor-chosen-password' where id=$1`,[sponsor]);
  await as('authenticated',sponsor);
  assert.equal((await db.query<Record<string,unknown>>('select * from public.financial_ledger')).rows.length,1);
  assert.equal((await db.query<Record<string,unknown>>('select * from public.profiles')).rows.length,1,'sponsor sees only their own profile');
  await as('authenticated',other);
  assert.equal((await db.query<Record<string,unknown>>('select * from public.financial_ledger')).rows.length,0,'another sponsor cannot see the first sponsor donation');
  await as('postgres');
  const failed=randomUUID(),failedRequest=randomUUID();
  await authUser(failed,'failed@example.test',failedRequest);
  await as('service_role');
  await assert.rejects(rpc('provision_account',[admin,failed,failedRequest,{role:'donor',full_name:'Rollback Sponsor',email:'failed@example.test',donation:{amount:-1,description:'Invalid amount'}}]),/Invalid initial donation/);
  const rolledBack=(await db.query<Record<string,unknown>>(`select role,status,requires_password_setup from public.profiles where id=$1`,[failed])).rows[0];
  assert.equal(rolledBack.status,'pending','failed transaction leaves no approved account');
  assert.equal((await db.query<Record<string,unknown>>(`select * from public.account_invitations where user_id=$1`,[failed])).rows.length,0);
  assert.equal(rolledBack.requires_password_setup,true,'an interrupted provisioning attempt remains locked');
  const resumedRequest=randomUUID();
  assert.equal((await rpc('provisioning_context',[admin,resumedRequest,'failed@example.test'])).rows[0].result,failed);
  await rpc('provision_account',[admin,failed,resumedRequest,{role:'donor',full_name:'Resumed Sponsor',email:'failed@example.test',phone:'',donation:{amount:500,description:'Recovered transaction'}}]);
  assert.equal((await db.query<Record<string,unknown>>(`select * from public.financial_ledger where donor_id=$1`,[failed])).rows.length,1,'an interrupted Auth creation can safely resume from a reopened form');
 } finally { await db.close(); }
});
